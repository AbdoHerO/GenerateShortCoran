"""Storyboard director: writes storyboard/<id>.json for a passage that fetch_data.py has already fetched.

  --mode auto    No AI. Calm ambient scenes, chapters by recitation length, no glosses (add them in the app).
  --mode claude  Claude (Anthropic API) reads the verses, translation and tafsir, then writes chapters, titles,
                 scenes and glosses. Every draft goes through verify.check(); failures are sent back for repair
                 (max 2 rounds). Anything that still fails is REMOVED, never forced through.

The director never writes Quranic text: the storyboard refers to words by verse + position only.
Usage: python pipeline/direct.py --id 26_60-68 --mode claude --style story
"""
import argparse, json, pathlib, re, sys, time

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "pipeline"))
from fetch_data import load_env  # noqa: E402
import verify  # noqa: E402

CAT = json.loads((ROOT / "renderer" / "js" / "scene_catalog.json").read_text(encoding="utf-8"))
TAFSIR_LABELS = {"16": "التفسير الميسر", "91": "تفسير السعدي"}
PRICES = {"claude-opus-5-5": (4.0, 20.0), "claude-sonnet-5-5": (2.0, 10.0), "claude-haiku-5-5": (0.10, 0.50)}  # $/MTok in, out
DIRECTOR_AREAS = {"storyboard", "scenes", "gloss", "fonts"}


def progress(**kw):
    print("@@ " + json.dumps(kw, ensure_ascii=False), flush=True)


# ---------------------------------------------------------------- shared helpers
def load(pid):
    data_dir = ROOT / "data" / pid
    src = json.loads((data_dir / "source.json").read_text(encoding="utf-8"))
    return data_dir, src


def words_of(v):
    return [w for w in v["words"] if w["char_type_name"] == "word"]


def verse_times(src):
    """Per verse: (start_s, end_s) of the recited words, relative to the first verse's first word."""
    T = {t["verse_key"]: t for t in src["recitation"]["timestamps"]}
    out, t0 = {}, None
    for v in src["verses"]:
        segs = T[v["verse_key"]]["segments"]
        a, b = min(s[1] for s in segs) / 1000, max(s[2] for s in segs) / 1000
        t0 = a if t0 is None else t0
        out[v["verse_number"]] = (a - t0, b - t0)
    return out, T, t0


def base_storyboard(pid, src):
    m = src["meta"]
    cat = json.loads((ROOT / "data" / "catalog.json").read_text(encoding="utf-8")) if (ROOT / "data" / "catalog.json").exists() else {"reciters": []}
    rec = next((r for r in cat["reciters"] if r["id"] == m["recitation_id"]), None)
    reciter_en = (rec or {}).get("name_en") or (src.get("reciter_en") or {}).get("name", "").replace("`", "'")
    return {
        "_comment": "Generated by the platform director. Quranic text is NEVER written here: words are referenced by verse + position.",
        "passage": {"chapter": m["chapter"], "from": m["from"], "to": m["to"]},
        "data_dir": f"data/{pid}",
        "recitation_id": m["recitation_id"],
        "intro_s": 1.4,
        "outro_s": 4.6,
        "tafsir_labels": TAFSIR_LABELS,
        "tafsir_expect": {"16": "Muyassar", "91": "Sa'di"},
        "translation_expect": "Saheeh International",
        "credits": {
            "reciter_ar": (rec or {}).get("name_ar") or reciter_en,
            "reciter_en": reciter_en,
            "translation_en": "Translation: Saheeh International",
            "data_en": "Text, audio timings & tafsir: Quran Foundation (quran.com)",
        },
        "timing_corrections": [],
        "chapters": [],
        "glosses": [],
    }


def group_verses(times, target=16.0, max_n=4):
    """Consecutive verse groups of roughly `target` seconds of recitation."""
    nums = sorted(times)
    groups, cur, acc = [], [], 0.0
    for n in nums:
        d = times[n][1] - times[n][0]
        if cur and (acc + d > target * 1.5 or len(cur) >= max_n):
            groups.append(cur); cur, acc = [], 0.0
        cur.append(n); acc += d
        if acc >= target:
            groups.append(cur); cur, acc = [], 0.0
    if cur:
        if groups and sum(times[n][1] - times[n][0] for n in cur) < 5:
            groups[-1] += cur
        else:
            groups.append(cur)
    return groups


# ---------------------------------------------------------------- auto director (no AI)
MOOD_WORDS = [
    ("rain", r"\brain\b|water from the sky|clouds"),
    ("sea", r"\bsea\b|\bships?\b|\bocean\b|\bwaves?\b"),
    ("night_sky", r"\bnight\b|\bstars?\b|\bmoon\b"),
    ("mountains", r"\bmountains?\b"),
    ("dawn", r"\bdawn\b|\bmorning\b|\bsunrise\b|\bday\b"),
]
ROTATION = ["dawn", "geometric", "light", "night_sky", "mountains", "sea"]


def auto(pid, src):
    sb = base_storyboard(pid, src)
    times, _, _ = verse_times(src)
    title = "سورة " + src["chapter"]["name_arabic"]
    tr = {v["verse_number"]: verify.clean_translation(v["translations"][0]["text"]) for v in src["verses"]}
    used = []
    for i, g in enumerate(group_verses(times)):
        text = " ".join(tr[n] for n in g)
        mood = next((m for m, rx in MOOD_WORDS if re.search(rx, text, re.I) and m not in used[-1:]), None)
        if not mood:
            mood = next(m for m in ROTATION[i % len(ROTATION):] + ROTATION if m not in used[-1:])
        used.append(mood)
        sb["chapters"].append({"id": f"c{i + 1}", "title": title, "verses": g, "scene": "ambient", "params": {"mood": mood}})
    sb["director"] = {"mode": "auto", "notes": "Calm visuals chosen automatically. Chapter titles are the surah name; edit them in the app if you like."}
    return sb


# ---------------------------------------------------------------- Claude director
def schema():
    amb, stg = CAT["ambient"], CAT["stage"]
    I, S = {"type": "integer"}, {"type": "string"}
    obj = lambda props: {"type": "object", "properties": props, "required": list(props), "additionalProperties": False}
    actor = obj({"id": S, "type": {"type": "string", "enum": list(stg["actors"])}, "label": S,
                 "place": {"type": "string", "enum": stg["places"]}, "count": I, "pose": {"type": "string", "enum": list(stg["poses"])},
                 "enter_verse": I, "enter_word": I, "exit_verse": I, "exit_word": I})
    event = obj({"type": {"type": "string", "enum": list(stg["events"])}, "at_verse": I, "at_word": I, "until_verse": I, "until_word": I})
    chapter = obj({"title": S, "verses": {"type": "array", "items": I}, "scene": {"type": "string", "enum": ["ambient", "stage"]},
                   "mood": {"type": "string", "enum": list(amb["moods"]) + [""]},
                   "setting": {"type": "string", "enum": list(stg["settings"]) + [""]},
                   "time": {"type": "string", "enum": stg["times"] + [""]},
                   "actors": {"type": "array", "items": actor}, "events": {"type": "array", "items": event}})
    gloss = obj({"verse": I, "word_from": I, "word_to": I, "tafsir": {"type": "integer", "enum": [16, 91]}, "excerpt": S, "target": S,
                 "tone": {"type": "string", "enum": ["red", "green", "blue", "amber"]}})
    return obj({"chapters": {"type": "array", "items": chapter}, "glosses": {"type": "array", "items": gloss}, "reviewer_notes": S})


def system_prompt(style):
    amb, stg = CAT["ambient"], CAT["stage"]
    moods = "\n".join(f"  - {k}: {v['label']} - use for {v['use']}" for k, v in amb["moods"].items())
    settings = ", ".join(stg["settings"])
    actors = "\n".join(f"  - {k}: {v['label']}" for k, v in stg["actors"].items())
    events = "\n".join(f"  - {k}: {v}" for k, v in stg["events"].items())
    poses = "; ".join(f"{k} = {v}" for k, v in stg["poses"].items())
    rules = "\n".join(f"- {r}" for r in CAT["rules"])
    style_rule = ("STYLE = story: use 'stage' for chapters that narrate an event of this world (stories of prophets and nations); "
                  "use 'ambient' for everything else." if style == "story" else
                  "STYLE = calm: use ONLY 'ambient' scenes (set setting='', time='', actors=[], events=[]).")
    return f"""You direct short vertical (9:16) Quran recitation videos. Each video shows an illustrated scene in a rounded frame, a chapter title above it, the verse card with word-by-word highlighting, the English translation, and short tafsir glosses that pop up when a key word is recited, with an arrow pointing into the scene.

You write ONLY the storyboard. The Quranic text, translation, recitation audio and word timings are fixed (Quran Foundation dataset) and are drawn exactly as received. You never write Quranic text: you refer to words only by verse number and word position.

# Absolute rules (accuracy and adab come first)
1. Never write, quote or paraphrase Quranic text anywhere: not in titles, glosses or labels.
2. A gloss excerpt is copied character-for-character from the tafsir text given for THAT verse: one contiguous substring, identical spelling, identical diacritics or lack of them, identical punctuation. Pick the tafsir's explanation words, never its quotation of the verse. Never include text inside {{ }} or ﴿ ﴾. Never pick an excerpt that contains two consecutive words of the passage's verses, or a fully vocalised Quran word. Maximum 64 characters; aim for 15-45. A short, clear excerpt beats a long one.
3. Picture rules:
{rules}
4. If you are unsure whether a passage narrates an event of this world, use 'ambient'.

# {style_rule}

# Chapters
- Consecutive verses, covering every verse of the passage exactly once, in order. One chapter = one beat. Aim for 8-25 s of recitation per chapter (durations are given). A long verse can be its own chapter; a one-verse passage is one chapter.
- title: 2-4 Arabic words in Modern Standard Arabic, no diacritics, max 28 characters: a descriptive heading for the beat (examples of the style: "مطاردة فرعون", "يقين موسى", "انفلاق البحر", "آية وعبرة"). It must not quote the Quran.
- scene 'ambient': set mood; setting='', time='', actors=[], events=[]. Moods:
{moods}
- scene 'stage': set setting ({settings}), time (day, dawn, dusk, night), actors and events; mood=''. Keep it simple: 1-3 actors, 0-2 events. Consecutive stage chapters of one story should keep the same setting unless the story moves.
  Actors (id = short lowercase slug, unique within the chapter, e.g. "musa", "army", "people"; never "center", "sky", "ground"):
{actors}
  label: ONLY for prophet / angel / honored, Arabic letters and spaces only (e.g. "موسى عليه السلام", "الملائكة", "مريم عليها السلام"); every other actor has label "", except a king who is Pharaoh: label "فرعون" (not drawn; it selects the Egyptian look). count: 1 for prophet/honored/king/ship/camel, 2-12 for groups. place: left, center or right. pose: {poses}.
  Events:
{events}
  How events behave: only the first event of each type in a chapter is used. blast, stones, quake and flood strike only disbelievers, soldiers and the king (they grey out and fade); believers, people and light drops are spared. sea_part works on sea_shore (and splits the water on river). ruin collapses buildings only on city and palace. The light beam falls on the first prophet/honored actor, otherwise on the believers. Stones keep falling until 'until' (set it when the verse moves on).
  Timing references are (verse, word) inside THIS chapter's verses, at the word where the verse states the thing. enter_verse/enter_word = 0/0 means present from the start; exit 0/0 = never leaves; until 0/0 = lasts to the chapter end. Only illustrate what the verses (and tafsir) state; do not invent events.

# Glosses
- Roughly one gloss per one or two verses, on the word(s) whose meaning most helps a viewer: unusual words, key concepts, who or what a pronoun refers to. None where there is nothing worth explaining.
- verse, word_from..word_to: word positions inside that verse (see the numbered word list).
- tafsir: 16 (التفسير الميسر, concise; preferred) or 91 (تفسير السعدي) when it explains better. The excerpt must come from that tafsir's text for that same verse.
- target: an anchor of the chapter's scene for the arrow, or "" for no arrow. ambient anchors: center, sky, light, ground. stage anchors: center, sky, ground and the chapter's actor ids. Point at what the word is about, and only at an actor that is visible at that moment (a 'flee' actor leaves the stage; an actor before its 'enter' or after its 'exit' is hidden). An actor who must stay visible should 'stand' or 'gather', not 'flee'.
- tone: red = punishment, warning, disbelief; green = mercy, faith, believers, reward; blue = neutral explanation or description; amber = time, place, emphasis, a sign.
- Gloss start words must be at least 1.2 s apart (word start times are given as @seconds).

# reviewer_notes
Two to four short English sentences for the human reviewer: what you chose and what they should double-check."""


def user_prompt(src, style):
    times, T, t0 = verse_times(src)
    m, ch = src["meta"], src["chapter"]
    lines = [f"PASSAGE: Surah {m['chapter']} {src['chapter_en']['name_simple']} ({ch['name_arabic']}), verses {m['from']}-{m['to']}.",
             f"STYLE: {style}", ""]
    prev = {}
    for v in src["verses"]:
        n, k = v["verse_number"], v["verse_key"]
        a, b = times[n]
        first_t = {}
        for s in T[k]["segments"]:
            first_t.setdefault(s[0], s[1] / 1000 - t0)
        ws = " | ".join(f"{w['position']} {w['text_uthmani']} @{first_t.get(w['position'], a):.1f}" for w in words_of(v))
        lines += [f"## VERSE {k}  (recitation {a:.1f}-{b:.1f} s, {b - a:.1f} s)",
                  f"words: {ws}",
                  f"translation: {verify.clean_translation(v['translations'][0]['text'])}"]
        for tid, label in TAFSIR_LABELS.items():
            text = verify.nfc(verify.strip_html(src["tafsirs"][tid][k]["text"]))
            if text and prev.get(tid, (None,))[0] == text:
                lines.append(f"tafsir {tid} ({label}): [identical to the text under {prev[tid][1]}]")
            else:
                lines.append(f"tafsir {tid} ({label}): {text or '[empty]'}")
                prev[tid] = (text, k)
        lines.append("")
    return "\n".join(lines)


def to_storyboard(pid, src, out):
    sb = base_storyboard(pid, src)
    ref = lambda v, w: [v, w] if v and w else None
    for i, c in enumerate(out["chapters"]):
        if c["scene"] == "ambient":
            params = {"mood": c["mood"]}
        else:
            params = {"setting": c["setting"], "time": c["time"],
                      "actors": [{"id": a["id"], "type": a["type"], "label": a["label"].strip(), "place": a["place"], "count": a["count"],
                                  "pose": a["pose"], "enter": ref(a["enter_verse"], a["enter_word"]), "exit": ref(a["exit_verse"], a["exit_word"])}
                                 for a in c["actors"]],
                      "events": [{"type": e["type"], "at": ref(e["at_verse"], e["at_word"]), "until": ref(e["until_verse"], e["until_word"])}
                                 for e in c["events"]]}
        sb["chapters"].append({"id": f"c{i + 1}", "title": c["title"].strip(), "verses": c["verses"], "scene": c["scene"], "params": params})
    for g in out["glosses"]:
        sb["glosses"].append({"verse": g["verse"], "words": [g["word_from"], g["word_to"]], "tafsir": g["tafsir"],
                              "excerpt": g["excerpt"].strip(), "target": g["target"].strip(), "tone": g["tone"]})
    return sb


def fails_of(results, areas=DIRECTOR_AREAS):
    return [m for lvl, area, m in results if lvl == "FAIL" and area in areas]


def sanitize(sb, src, data_dir, removed):
    """Last resort after the repair rounds: drop what still fails. Never invents replacements for Quran-related content."""
    verses = {v["verse_number"]: v for v in src["verses"]}
    fixed = []
    for c in sb["chapters"]:
        bad = []
        verify.check_scenes({**sb, "chapters": [c]}, verses, lambda *a: None, lambda area, msg: bad.append(msg), lambda *a: None)
        if bad:
            removed.append(f"chapter {c['id']} scene replaced by a calm visual ({'; '.join(bad)})")
            title = c["title"] if 0 < len(c["title"].strip()) <= 28 else "سورة " + src["chapter"]["name_arabic"]
            c = {**c, "title": title, "scene": "ambient", "params": {"mood": "light"}}
        fixed.append(c)
    sb["chapters"] = fixed
    keep = []
    for g in sb["glosses"]:
        res = verify.check({**sb, "glosses": keep + [g]}, src, data_dir)
        f = fails_of(res, {"gloss", "fonts"})
        if f:
            removed.append(f"gloss {g['verse']}:{g['words']} «{g['excerpt']}» removed: {f[-1]}")
        else:
            keep.append(g)
    sb["glosses"] = keep
    return sb


def claude(pid, src, data_dir, style, model):
    import anthropic
    env = load_env()
    key = env.get("ANTHROPIC_API_KEY")
    if not key:
        raise SystemExit("ANTHROPIC_API_KEY is not set in .env")
    client = anthropic.Anthropic(api_key=key, max_retries=3)
    system = system_prompt(style)
    messages = [{"role": "user", "content": [{"type": "text", "text": user_prompt(src, style), "cache_control": {"type": "ephemeral"}}]}]
    usage = {"input": 0, "output": 0, "cache_read": 0, "cache_write": 0}
    removed, sb, notes = [], None, ""
    structured = True
    for rnd in range(3):
        progress(step="direct", what="Claude is writing the storyboard" if rnd == 0 else f"Claude is fixing {len(last_fails)} issue(s) (round {rnd})")
        try:
            try:
                cfg = {"effort": "high", "format": {"type": "json_schema", "schema": schema()}} if structured else {"effort": "high"}
                sys_txt = system if structured else system + "\n\nReply with ONE JSON object only (no prose, no code fences) with keys chapters, glosses, reviewer_notes as described."
                with client.messages.stream(model=model, max_tokens=32000, system=sys_txt, messages=messages, output_config=cfg) as stream:
                    msg = stream.get_final_message()
            except anthropic.BadRequestError as e:
                if not structured or not re.search(r"schema|format|output_config", str(e), re.I):
                    raise
                structured = False   # this model/account rejected the schema: ask for plain JSON instead
                progress(step="direct", what="Retrying without structured output")
                with client.messages.stream(model=model, max_tokens=32000, messages=messages, output_config={"effort": "high"},
                                            system=system + "\n\nReply with ONE JSON object only (no prose, no code fences) with keys chapters, glosses, reviewer_notes as described.") as stream:
                    msg = stream.get_final_message()
        except anthropic.AuthenticationError:
            raise SystemExit("Claude API key was rejected (check ANTHROPIC_API_KEY in .env)")
        except anthropic.APIConnectionError as e:
            raise SystemExit(f"Could not reach the Claude API: {e}")
        except anthropic.APIStatusError as e:
            raise SystemExit(f"Claude API error {e.status_code}: {str(e)[:300]}")
        u = msg.usage
        usage["input"] += u.input_tokens; usage["output"] += u.output_tokens
        usage["cache_read"] += getattr(u, "cache_read_input_tokens", 0) or 0
        usage["cache_write"] += getattr(u, "cache_creation_input_tokens", 0) or 0
        if msg.stop_reason == "refusal":
            raise SystemExit("Claude declined to write this storyboard; use the simple director instead")
        if msg.stop_reason == "max_tokens":
            raise SystemExit("Claude's storyboard was cut off (passage too long?); try a shorter range")
        text = next((b.text for b in msg.content if b.type == "text"), "")
        try:
            out = json.loads(text)
        except json.JSONDecodeError:
            m = re.search(r"\{.*\}", text, re.S)   # tolerate fences or stray prose in the plain-JSON fallback
            if not m:
                raise SystemExit("Claude did not return a storyboard (no JSON found)")
            out = json.loads(m.group(0))
        notes = out.get("reviewer_notes", "")
        sb = to_storyboard(pid, src, out)
        res = verify.check(sb, src, data_dir)
        other = fails_of(res, {"text", "audio", "resources"})
        if other:   # not the director's job; the verify step will block the project with these
            break
        last_fails = fails_of(res)
        progress(step="direct", what=f"draft {rnd + 1}: {len(last_fails)} issue(s) found by the verifier")
        if not last_fails:
            break
        if rnd == 2:
            break
        messages += [{"role": "assistant", "content": msg.content},
                     {"role": "user", "content": "The verifier rejected these items:\n- " + "\n- ".join(last_fails) +
                      "\n\nReturn the complete corrected storyboard. Fix each item; if a gloss cannot be made verbatim and "
                      "explanation-only, drop that gloss. Keep everything that passed unchanged."}]
    sb = sanitize(sb, src, data_dir, removed)
    pin, pout = PRICES.get(model, (4.0, 20.0))
    cost = (usage["input"] * pin + usage["cache_write"] * pin * 1.25 + usage["cache_read"] * pin * 0.1 + usage["output"] * pout) / 1e6
    sb["director"] = {"mode": "claude", "model": model, "style": style, "rounds": rnd + 1, "usage": usage,
                      "cost_usd": round(cost, 3), "notes": notes, "removed": removed}
    return sb


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--id", required=True)
    ap.add_argument("--mode", choices=["auto", "claude"], default="auto")
    ap.add_argument("--style", choices=["story", "calm"], default="story")
    ap.add_argument("--model", default=None)
    a = ap.parse_args()
    data_dir, src = load(a.id)
    t0 = time.time()
    if a.mode == "claude":
        model = a.model or load_env().get("CLAUDE_MODEL") or "claude-opus-5-5"
        sb = claude(a.id, src, data_dir, a.style, model)
    else:
        sb = auto(a.id, src)
    out = ROOT / "storyboard" / f"{a.id}.json"
    out.parent.mkdir(exist_ok=True)
    out.write_text(json.dumps(sb, ensure_ascii=False, indent=1), encoding="utf-8")
    d = sb["director"]
    progress(step="direct", done=True, mode=d["mode"], cost_usd=d.get("cost_usd"), removed=len(d.get("removed", [])))
    print(f"storyboard written: {out} ({len(sb['chapters'])} chapters, {len(sb['glosses'])} glosses, {time.time() - t0:.0f}s"
          + (f", ${d['cost_usd']}" if d.get("cost_usd") is not None else "") + ")")


if __name__ == "__main__":
    main()
